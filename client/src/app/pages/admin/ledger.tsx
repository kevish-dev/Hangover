import { useEffect, useMemo, useState, useRef } from "react";
import { useMutation, useQuery, useQueryClient } from "@tanstack/react-query";
import { format } from "date-fns";
import {
  BookOpen,
  Loader2,
  Plus,
  Search,
  Trash2,
  X,
  FileSpreadsheet,
} from "lucide-react";
import { toast } from "sonner";
import { apiClient } from "../../../lib/axios";
import { Button } from "../../components/ui/button";
import { Input } from "../../components/ui/input";
import { getErrorMessage, showErrorToast } from "../../../lib/errors";
import { SyncIndicator } from "../../components/ui/sync-indicator";

type TripOption = { id: string; title: string };

type Entry = {
  id: string;
  type: "INCOME" | "EXPENSE";
  scope: string;
  source: string;
  category: string;
  amount: string | number;
  description?: string | null;
  entryDate: string;
  isAutoGenerated: boolean;
  trip?: { id: string; title: string } | null;
  crmTrip?: { id: string; name: string } | null;
  festival?: { id: string; title: string } | null;
  crmFestival?: { id: string; name: string } | null;
  booking?: {
    id: string;
    bookingReference: string;
    crmTrip?: { id: string; name: string } | null;
  } | null;
  tripId?: string | null;
  crmTripId?: string | null;
  festivalId?: string | null;
  crmFestivalId?: string | null;
  bookingId?: string | null;
};

type Ledger = {
  entries: Entry[];
  summary: {
    tripIncome: number;
    tripExpense: number;
    otherIncome: number;
    otherExpense: number;
    totalIncome: number;
    totalExpense: number;
    netBalance: number;
  };
};

const CATEGORIES = [
  "HOTEL",
  "TRANSPORT",
  "PERMIT",
  "VENDOR",
  "ACTIVITY",
  "DOCUMENTATION",
  "PAYMENT_COLLECTION",
  "SALARY",
  "MARKETING",
  "OFFICE_RENT",
  "SOFTWARE_SUBSCRIPTION",
  "OTHER_EXPENSE",
  "BOOKING_PAYMENT",
  "REFUND",
  "OTHER_INCOME",
];

const money = (value: unknown) =>
  `₹${Number(value || 0).toLocaleString("en-IN", { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;

export default function AdminLedgerPage() {
  const queryClient = useQueryClient();
  const [search, setSearch] = useState("");
  const [type, setType] = useState("");
  const [scope, setScope] = useState("");
  const [selectedTripId, setSelectedTripId] = useState("");

  const query = useQuery({
    queryKey: ["admin", "ledger"],
    queryFn: async () =>
      (await apiClient.get<Ledger>("/ledgers", { params: { limit: 1000 } }))
        .data,
  });

  const tripsQuery = useQuery({
    queryKey: ["admin", "ledger-trip-options"],
    queryFn: async ({ signal }) => (
      await apiClient.get<{ data: TripOption[] }>("/ledgers/trip-options", { signal })
    ).data.data,
  });

  const trips = tripsQuery.data;
  const tripOptionsUnavailable = tripsQuery.isError && !trips;
  const tripOptionIds = useMemo(() => new Set(trips?.map(({ id }) => id)), [trips]);

  const festivalsQuery = useQuery({
    queryKey: ["admin", "festivals", "all-combined"],
    queryFn: async () => {
      const [crmRes, legacyRes] = await Promise.allSettled([
        apiClient.get("/crm-festivals", { params: { limit: 500 } }),
        apiClient.get("/festivals", {
          params: { adminView: true, limit: 500 },
        }),
      ]);

      const crmFestivals =
        crmRes.status === "fulfilled"
          ? (crmRes.value.data?.data || crmRes.value.data || []).map(
              (f: any) => ({
                id: f.id,
                title: f.name || f.title,
              }),
            )
          : [];

      const legacyFestivals =
        legacyRes.status === "fulfilled"
          ? (legacyRes.value.data?.data || legacyRes.value.data || []).map(
              (f: any) => ({
                id: f.id,
                title: f.title || f.name,
              }),
            )
          : [];

      const crmIds = new Set(crmFestivals.map((f: any) => f.id));
      const filteredLegacy = legacyFestivals.filter(
        (f: any) => !crmIds.has(f.id),
      );

      return [...crmFestivals, ...filteredLegacy];
    },
  });

  const festivals = festivalsQuery.data || [];

  const bookingsQuery = useQuery({
    queryKey: ["admin", "bookings", "list"],
    queryFn: async () =>
      (await apiClient.get("/bookings", { params: { limit: 200 } })).data
        ?.data || [],
  });

  const bookings = bookingsQuery.data || [];

  useEffect(() => {
    if (query.isError)
      toast.error(getErrorMessage(query.error, "Ledger could not be loaded"), {
        id: "ledger-load-error",
      });
  }, [query.error, query.isError]);

  const allEntries = query.data?.entries || [];

  const entries = useMemo(() => {
    return allEntries.filter((entry) => {
      if (type && entry.type !== type) return false;
      if (scope && entry.scope !== scope) return false;
      if (selectedTripId) {
        const directTripId =
          entry.tripId ||
          entry.crmTripId ||
          entry.trip?.id ||
          entry.crmTrip?.id;
        const bookingTripId =
          (entry.booking as any)?.crmTripId ||
          (entry.booking as any)?.crmTrip?.id ||
          (entry.booking as any)?.tripId ||
          (entry.booking as any)?.trip?.id;
        if (directTripId !== selectedTripId && bookingTripId !== selectedTripId)
          return false;
      }
      const needle = search.trim().toLowerCase();
      if (!needle) return true;
      return [
        entry.category,
        entry.description,
        entry.source,
        entry.trip?.title,
        entry.crmTrip?.name,
        entry.festival?.title,
        entry.crmFestival?.name,
        entry.booking?.bookingReference,
        entry.booking?.crmTrip?.name,
      ]
        .filter(Boolean)
        .join(" ")
        .toLowerCase()
        .includes(needle);
    });
  }, [allEntries, type, scope, selectedTripId, search]);

  const selectedTrip = useMemo(() => {
    if (!selectedTripId) return null;
    return trips?.find((trip) => trip.id === selectedTripId) || null;
  }, [trips, selectedTripId]);

  const filteredSummary = useMemo(() => {
    let income = 0;
    let expense = 0;
    for (const entry of entries) {
      const amt = Number(entry.amount) || 0;
      if (entry.type === "INCOME") income += amt;
      else if (entry.type === "EXPENSE") expense += amt;
    }
    return {
      totalIncome: income,
      totalExpense: expense,
      netBalance: income - expense,
    };
  }, [entries]);

  const summary = query.data?.summary || {
    tripIncome: 0,
    tripExpense: 0,
    otherIncome: 0,
    otherExpense: 0,
    totalIncome: 0,
    totalExpense: 0,
    netBalance: 0,
  };

  const updateMutation = useMutation({
    mutationFn: async ({ id, data }: { id: string; data: Partial<Entry> }) => {
      await apiClient.patch(`/ledgers/entries/${id}`, data);
    },
    onSuccess: () =>
      queryClient.invalidateQueries({ queryKey: ["admin", "ledger"] }),
    onError: (err) => showErrorToast(err, "Failed to update entry"),
  });

  const createMutation = useMutation({
    mutationFn: async (data: Partial<Entry>) => {
      await apiClient.post("/ledgers/entries", data);
    },
    onSuccess: () => {
      queryClient.invalidateQueries({ queryKey: ["admin", "ledger"] });
      setNewRow({
        type: "EXPENSE",
        scope: "OTHER",
        category: "OTHER_EXPENSE",
        amount: "",
        description: "",
        entryDate: format(new Date(), "yyyy-MM-dd"),
        tripId: "",
        festivalId: "",
        bookingId: "",
      });
    },
    onError: (err) => showErrorToast(err, "Failed to create entry"),
  });

  const deleteMutation = useMutation({
    mutationFn: async (id: string) => {
      await apiClient.delete(`/ledgers/entries/${id}`);
    },
    onSuccess: () => {
      toast.success("Entry deleted");
      queryClient.invalidateQueries({ queryKey: ["admin", "ledger"] });
    },
    onError: (err) => showErrorToast(err, "Failed to delete entry"),
  });

  const [newRow, setNewRow] = useState<any>({
    type: "EXPENSE",
    scope: "OTHER",
    category: "OTHER_EXPENSE",
    amount: "",
    description: "",
    entryDate: format(new Date(), "yyyy-MM-dd"),
    tripId: "",
    festivalId: "",
    bookingId: "",
  });

  const handleCellChange = (entry: Entry, field: string, value: any) => {
    if (entry.isAutoGenerated) return;
    if (entry[field as keyof Entry] === value) return;
    updateMutation.mutate({ id: entry.id, data: { [field]: value } });
  };

  const handleNewRowSubmit = () => {
    const amount = Number(newRow.amount);
    if (!amount || amount <= 0)
      return toast.error("Amount must be greater than zero");
    if (!newRow.category.trim()) return toast.error("Category is required");

    createMutation.mutate({
      type: newRow.type,
      scope: newRow.scope,
      category: newRow.category,
      amount,
      description: newRow.description,
      entryDate: new Date(newRow.entryDate).toISOString(),
      tripId: newRow.scope === "TRIP" ? newRow.tripId : undefined,
      festivalId: newRow.scope === "FESTIVAL" ? newRow.festivalId : undefined,
      bookingId: newRow.scope === "BOOKING" ? newRow.bookingId : undefined,
    });
  };

  if (query.isLoading)
    return (
      <div className="flex min-h-[60vh] items-center justify-center">
        <Loader2 className="h-8 w-8 animate-spin text-[#781216]" />
      </div>
    );
  if (query.isError)
    return (
      <div className="rounded-2xl border border-red-200 bg-red-50 p-6 text-red-800">
        <h1 className="font-bold">Ledger could not be loaded</h1>
        <button
          type="button"
          onClick={() => query.refetch()}
          className="mt-3 text-sm font-semibold underline"
        >
          Try again
        </button>
      </div>
    );

  return (
    <div className="mx-auto max-w-[1500px] space-y-5 pb-12">
      <header className="flex flex-col md:flex-row md:items-end justify-between gap-4">
        <div>
          <h1 className="mt-1 text-2xl font-bold text-gray-950 sm:text-3xl flex items-center gap-2">
            Ledger
          </h1>
          <p className="mt-2 max-w-2xl text-sm leading-6 text-gray-600">
            All income and expenses across trips, festivals, and general
            operations.
          </p>
        </div>
      </header>

      <div className="grid gap-3 sm:grid-cols-2 xl:grid-cols-4">
        <div className="rounded-2xl border border-gray-200 bg-white p-4 shadow-sm">
          <p className="text-sm font-semibold text-gray-500 mb-1">
            Total Income
          </p>
          <p className="text-2xl font-bold text-emerald-600">
            {money(summary.totalIncome)}
          </p>
          <div className="mt-2 text-xs text-gray-400 flex justify-between">
            <span>Trips: {money(summary.tripIncome)}</span>
            <span>Other: {money(summary.otherIncome)}</span>
          </div>
        </div>
        <div className="rounded-2xl border border-gray-200 bg-white p-4 shadow-sm">
          <p className="text-sm font-semibold text-gray-500 mb-1">
            Total Expenses
          </p>
          <p className="text-2xl font-bold text-red-600">
            {money(summary.totalExpense)}
          </p>
          <div className="mt-2 text-xs text-gray-400 flex justify-between">
            <span>Trips: {money(summary.tripExpense)}</span>
            <span>Other: {money(summary.otherExpense)}</span>
          </div>
        </div>
        <div className="rounded-2xl border border-emerald-200 bg-emerald-50 p-4 shadow-sm xl:col-span-2 flex items-center justify-between">
          <div>
            <p className="text-sm font-semibold text-emerald-800 mb-1">
              Net Balance
            </p>
            <p
              className={`text-3xl font-bold ${summary.netBalance >= 0 ? "text-emerald-700" : "text-red-700"}`}
            >
              {summary.netBalance >= 0 ? "+" : ""}
              {money(summary.netBalance)}
            </p>
          </div>
        </div>
      </div>

      <div className="grid gap-3 rounded-2xl border border-gray-200 bg-white p-4 shadow-sm md:grid-cols-[1fr_220px_140px_140px]">
        <div className="relative">
          <Search className="pointer-events-none absolute left-3 top-1/2 h-4 w-4 -translate-y-1/2 text-gray-400" />
          <Input
            value={search}
            onChange={(e) => setSearch(e.target.value)}
            placeholder="Category, trip, booking, or description"
            className="pl-10"
          />
        </div>
        <div className="min-w-0">
          <select
            aria-label="Filter ledger by trip"
            value={selectedTripId}
            onChange={(e) => setSelectedTripId(e.target.value)}
            disabled={!trips}
            className="flex h-10 w-full rounded-md border border-input bg-background px-3 text-sm truncate font-medium"
          >
            <option value="">
              {tripOptionsUnavailable ? "Trip options unavailable" : tripsQuery.isPending ? "Loading trips…" : "Filter by Trip (All Trips)"}
            </option>
            {trips?.map(({ id, title }) => (
              <option key={id} value={id}>{title}</option>
            ))}
          </select>
          {tripOptionsUnavailable && (
            <button type="button" onClick={() => void tripsQuery.refetch()} disabled={tripsQuery.isFetching} className="mt-1 text-sm font-semibold underline">
              {tripsQuery.isFetching ? "Retrying…" : "Retry trip options"}
            </button>
          )}
        </div>
        <select
          value={type}
          onChange={(e) => setType(e.target.value)}
          className="flex h-10 rounded-md border border-input bg-background px-3 text-sm"
        >
          <option value="">All types</option>
          <option>INCOME</option>
          <option>EXPENSE</option>
        </select>
        <select
          value={scope}
          onChange={(e) => setScope(e.target.value)}
          className="flex h-10 rounded-md border border-input bg-background px-3 text-sm"
        >
          <option value="">All scopes</option>
          <option value="TRIP">Trip</option>
          <option value="BOOKING">Booking</option>
          <option value="FESTIVAL">Festival</option>
          <option value="OTHER">Other</option>
        </select>
      </div>

      {(selectedTripId || scope === "TRIP" || search.trim()) && (
        <div className="rounded-2xl border border-blue-200 bg-blue-50/70 p-4 shadow-sm flex flex-col md:flex-row md:items-center justify-between gap-4">
          <div>
            <p className="text-xs font-bold uppercase tracking-[0.16em] text-blue-700">
              {selectedTripId
                ? "Trip Financial Summary"
                : "Filtered Entries Financials"}
            </p>
            <h3 className="text-lg font-bold text-gray-900 mt-0.5">
              {selectedTrip
                ? selectedTrip.title
                : `${entries.length} Filtered Entries`}
            </h3>
            <p className="text-xs text-gray-500">
              Showing calculated totals for the current selection
            </p>
          </div>
          <div className="flex flex-wrap items-center gap-6">
            <div>
              <p className="text-xs font-semibold text-gray-500">
                Total Income
              </p>
              <p className="text-xl font-bold text-emerald-600">
                {money(filteredSummary.totalIncome)}
              </p>
            </div>
            <div className="hidden sm:block h-8 w-px bg-blue-200" />
            <div>
              <p className="text-xs font-semibold text-gray-500">
                Total Expense
              </p>
              <p className="text-xl font-bold text-red-600">
                {money(filteredSummary.totalExpense)}
              </p>
            </div>
            <div className="hidden sm:block h-8 w-px bg-blue-200" />
            <div>
              <p className="text-xs font-semibold text-gray-500">Net Balance</p>
              <p
                className={`text-xl font-bold ${filteredSummary.netBalance >= 0 ? "text-emerald-700" : "text-red-700"}`}
              >
                {filteredSummary.netBalance >= 0 ? "+" : ""}
                {money(filteredSummary.netBalance)}
              </p>
            </div>
          </div>
        </div>
      )}

      <div className="flex justify-end items-center mb-3">
        <SyncIndicator
          isMutating={
            createMutation.isPending ||
            updateMutation.isPending ||
            deleteMutation.isPending
          }
          isError={
            createMutation.isError ||
            updateMutation.isError ||
            deleteMutation.isError
          }
        />
      </div>

      <div className="rounded-xl border border-gray-200 bg-white shadow-sm overflow-hidden flex flex-col">
        <div className="overflow-x-auto">
          <table className="w-full text-left text-sm border-collapse">
            <thead className="bg-gray-100 border-b border-gray-300">
              <tr>
                <th className="px-3 py-2 font-semibold text-gray-600 border-r border-gray-300 w-32">
                  Date
                </th>
                <th className="px-3 py-2 font-semibold text-gray-600 border-r border-gray-300 w-32">
                  Type
                </th>
                <th className="px-3 py-2 font-semibold text-gray-600 border-r border-gray-300 w-32">
                  Scope
                </th>
                <th className="px-3 py-2 font-semibold text-gray-600 border-r border-gray-300 w-48">
                  Context (Trip)
                </th>
                <th className="px-3 py-2 font-semibold text-gray-600 border-r border-gray-300 w-40">
                  Category
                </th>
                <th className="px-3 py-2 font-semibold text-gray-600 border-r border-gray-300">
                  Description
                </th>
                <th className="px-3 py-2 font-semibold text-gray-600 border-r border-gray-300 w-36 text-right">
                  Amount
                </th>
                <th className="px-2 py-2 font-semibold text-gray-600 w-10 text-center"></th>
              </tr>
            </thead>
            <tbody className="divide-y divide-gray-200">
              {/* Add New Row */}
              <tr className="bg-emerald-50/30 border-b-2 border-emerald-200">
                <td className="border-r border-gray-200 p-0">
                  <input
                    type="date"
                    value={newRow.entryDate}
                    onChange={(e) =>
                      setNewRow({ ...newRow, entryDate: e.target.value })
                    }
                    className="w-full h-full min-h-10 px-3 bg-transparent outline-none focus:bg-emerald-100 focus:ring-1 focus:ring-emerald-500"
                  />
                </td>
                <td className="border-r border-gray-200 p-0">
                  <select
                    value={newRow.type}
                    onChange={(e) =>
                      setNewRow({
                        ...newRow,
                        type: e.target.value as "INCOME" | "EXPENSE",
                      })
                    }
                    className={`w-full h-full min-h-10 px-2 bg-transparent outline-none focus:bg-emerald-100 focus:ring-1 focus:ring-emerald-500 font-semibold ${newRow.type === "INCOME" ? "text-emerald-700" : "text-red-700"}`}
                  >
                    <option value="INCOME">INCOME</option>
                    <option value="EXPENSE">EXPENSE</option>
                  </select>
                </td>
                <td className="border-r border-gray-200 p-0">
                  <select
                    value={newRow.scope}
                    onChange={(e) =>
                      setNewRow({ ...newRow, scope: e.target.value })
                    }
                    className="w-full h-full min-h-10 px-2 bg-transparent outline-none focus:bg-emerald-100 focus:ring-1 focus:ring-emerald-500"
                  >
                    <option value="TRIP">TRIP</option>
                    <option value="FESTIVAL">FESTIVAL</option>
                    <option value="BOOKING">BOOKING</option>
                    <option value="OTHER">OTHER</option>
                  </select>
                </td>
                <td className="border-r border-gray-200 p-0 relative">
                  {newRow.scope === "TRIP" ? (
                    <select
                      value={newRow.tripId}
                      disabled={!trips}
                      onChange={(e) =>
                        setNewRow({ ...newRow, tripId: e.target.value })
                      }
                      className="w-full h-full min-h-10 px-2 bg-transparent outline-none focus:bg-emerald-100 focus:ring-1 focus:ring-emerald-500 text-xs"
                    >
                      <option value="">Select trip...</option>
                      {trips?.map((t) => (
                        <option key={t.id} value={t.id}>
                          {t.title}
                        </option>
                      ))}
                    </select>
                  ) : newRow.scope === "FESTIVAL" ? (
                    <select
                      value={newRow.festivalId}
                      onChange={(e) =>
                        setNewRow({ ...newRow, festivalId: e.target.value })
                      }
                      className="w-full h-full min-h-10 px-2 bg-transparent outline-none focus:bg-emerald-100 focus:ring-1 focus:ring-emerald-500 text-xs"
                    >
                      <option value="">Select festival...</option>
                      {festivals.map((f: any) => (
                        <option key={f.id} value={f.id}>
                          {f.title}
                        </option>
                      ))}
                    </select>
                  ) : newRow.scope === "BOOKING" ? (
                    <select
                      value={newRow.bookingId}
                      onChange={(e) =>
                        setNewRow({ ...newRow, bookingId: e.target.value })
                      }
                      className="w-full h-full min-h-10 px-2 bg-transparent outline-none focus:bg-emerald-100 focus:ring-1 focus:ring-emerald-500 text-xs"
                    >
                      <option value="">Select booking...</option>
                      {bookings.map((b: any) => (
                        <option key={b.id} value={b.id}>
                          {b.bookingReference}
                        </option>
                      ))}
                    </select>
                  ) : (
                    <div className="w-full h-full min-h-10 px-3 flex items-center text-emerald-600/50 italic">
                      N/A
                    </div>
                  )}
                </td>
                <td className="border-r border-gray-200 p-0">
                  <select
                    value={newRow.category}
                    onChange={(e) =>
                      setNewRow({ ...newRow, category: e.target.value })
                    }
                    className="w-full h-full min-h-10 px-2 bg-transparent outline-none focus:bg-emerald-100 focus:ring-1 focus:ring-emerald-500 text-xs"
                  >
                    <option value="">Category...</option>
                    {CATEGORIES.map((c) => (
                      <option key={c} value={c}>
                        {c}
                      </option>
                    ))}
                  </select>
                </td>
                <td className="border-r border-gray-200 p-0">
                  <input
                    type="text"
                    value={newRow.description}
                    onChange={(e) =>
                      setNewRow({ ...newRow, description: e.target.value })
                    }
                    onKeyDown={(e) => e.key === "Enter" && handleNewRowSubmit()}
                    placeholder="New description..."
                    className="w-full h-full min-h-10 px-3 bg-transparent outline-none focus:bg-emerald-100 focus:ring-1 focus:ring-emerald-500"
                  />
                </td>
                <td className="border-r border-gray-200 p-0">
                  <input
                    type="number"
                    step="0.01"
                    value={newRow.amount}
                    onChange={(e) =>
                      setNewRow({ ...newRow, amount: e.target.value })
                    }
                    onKeyDown={(e) => e.key === "Enter" && handleNewRowSubmit()}
                    placeholder="Amount..."
                    className={`w-full h-full min-h-10 px-3 bg-transparent outline-none text-right font-mono font-medium focus:bg-emerald-100 focus:ring-1 focus:ring-emerald-500 ${newRow.type === "INCOME" ? "text-emerald-700" : "text-red-700"}`}
                  />
                </td>
                <td className="p-0 text-center align-middle">
                  <button
                    onClick={handleNewRowSubmit}
                    disabled={createMutation.isPending}
                    className="text-emerald-600 hover:text-emerald-800 transition-colors mx-auto p-1.5"
                    title="Add Entry"
                  >
                    {createMutation.isPending ? (
                      <Loader2 className="w-4 h-4 animate-spin" />
                    ) : (
                      <Plus className="w-5 h-5" />
                    )}
                  </button>
                </td>
              </tr>

              {entries.map((entry) => (
                <tr
                  key={entry.id}
                  className={`group ${entry.isAutoGenerated ? "bg-gray-50/50" : "hover:bg-blue-50/30"}`}
                >
                  <td className="border-r border-gray-200 p-0">
                    <input
                      type="date"
                      disabled={entry.isAutoGenerated}
                      defaultValue={format(
                        new Date(entry.entryDate),
                        "yyyy-MM-dd",
                      )}
                      onBlur={(e) =>
                        handleCellChange(entry, "entryDate", e.target.value)
                      }
                      className="w-full h-full min-h-10 px-3 bg-transparent outline-none focus:bg-blue-50 focus:ring-1 focus:ring-blue-500 disabled:opacity-50 disabled:cursor-not-allowed"
                    />
                  </td>
                  <td className="border-r border-gray-200 p-0">
                    <select
                      disabled={entry.isAutoGenerated}
                      defaultValue={entry.type}
                      onChange={(e) =>
                        handleCellChange(entry, "type", e.target.value)
                      }
                      className={`w-full h-full min-h-10 px-2 bg-transparent outline-none focus:bg-blue-50 focus:ring-1 focus:ring-blue-500 font-semibold disabled:opacity-50 disabled:cursor-not-allowed ${entry.type === "INCOME" ? "text-emerald-700" : "text-red-700"}`}
                    >
                      <option value="INCOME">INCOME</option>
                      <option value="EXPENSE">EXPENSE</option>
                    </select>
                  </td>
                  <td className="border-r border-gray-200 p-0">
                    <select
                      disabled={entry.isAutoGenerated}
                      defaultValue={entry.scope}
                      onChange={(e) =>
                        handleCellChange(entry, "scope", e.target.value)
                      }
                      className="w-full h-full min-h-10 px-2 bg-transparent outline-none focus:bg-blue-50 focus:ring-1 focus:ring-blue-500 disabled:opacity-50 disabled:cursor-not-allowed"
                    >
                      <option value="TRIP">TRIP</option>
                      <option value="BOOKING">BOOKING</option>
                      <option value="FESTIVAL">FESTIVAL</option>
                      <option value="OTHER">OTHER</option>
                    </select>
                  </td>
                  <td className="border-r border-gray-200 p-0 relative">
                    {entry.isAutoGenerated ? (
                      <div className="w-full h-full min-h-10 px-3 flex items-center text-gray-500 truncate text-xs">
                        {entry.trip?.title ||
                          entry.crmTrip?.name ||
                          entry.festival?.title ||
                          entry.crmFestival?.name ||
                          entry.booking?.crmTrip?.name ||
                          entry.booking?.bookingReference ||
                          "N/A"}
                      </div>
                    ) : entry.scope === "TRIP" ? (
                      <select
                        defaultValue={entry.crmTripId || entry.tripId || ""}
                        disabled={!trips}
                        onChange={(e) =>
                          handleCellChange(entry, "tripId", e.target.value)
                        }
                        className="w-full h-full min-h-10 px-2 bg-transparent outline-none focus:bg-blue-50 focus:ring-1 focus:ring-blue-500 text-xs"
                      >
                        <option value="">Select trip...</option>
                        {entry.crmTrip && !tripOptionIds.has(entry.crmTrip.id) && (
                          <option value={entry.crmTrip.id}>{entry.crmTrip.name}</option>
                        )}
                        {entry.trip && !tripOptionIds.has(entry.trip.id) && (
                          <option value={entry.trip.id}>{entry.trip.title}</option>
                        )}
                        {trips?.map((t) => (
                          <option key={t.id} value={t.id}>
                            {t.title}
                          </option>
                        ))}
                      </select>
                    ) : entry.scope === "FESTIVAL" ? (
                      <select
                        defaultValue={
                          entry.crmFestivalId || entry.festivalId || ""
                        }
                        onChange={(e) =>
                          handleCellChange(entry, "festivalId", e.target.value)
                        }
                        className="w-full h-full min-h-10 px-2 bg-transparent outline-none focus:bg-blue-50 focus:ring-1 focus:ring-blue-500 text-xs"
                      >
                        <option value="">Select festival...</option>
                        {festivals.map((f: any) => (
                          <option key={f.id} value={f.id}>
                            {f.title}
                          </option>
                        ))}
                      </select>
                    ) : entry.scope === "BOOKING" ? (
                      <select
                        defaultValue={entry.bookingId || ""}
                        onChange={(e) =>
                          handleCellChange(entry, "bookingId", e.target.value)
                        }
                        className="w-full h-full min-h-10 px-2 bg-transparent outline-none focus:bg-blue-50 focus:ring-1 focus:ring-blue-500 text-xs"
                      >
                        <option value="">Select booking...</option>
                        {bookings.map((b: any) => (
                          <option key={b.id} value={b.id}>
                            {b.bookingReference}
                          </option>
                        ))}
                      </select>
                    ) : (
                      <div className="w-full h-full min-h-10 px-3 flex items-center text-gray-400 italic">
                        Not applicable
                      </div>
                    )}
                  </td>
                  <td className="border-r border-gray-200 p-0">
                    {entry.isAutoGenerated ? (
                      <div className="w-full h-full min-h-10 px-3 flex items-center text-gray-700 font-medium truncate">
                        {entry.category}
                      </div>
                    ) : (
                      <select
                        defaultValue={entry.category}
                        onChange={(e) =>
                          handleCellChange(entry, "category", e.target.value)
                        }
                        className="w-full h-full min-h-10 px-2 bg-transparent outline-none focus:bg-blue-50 focus:ring-1 focus:ring-blue-500 text-xs"
                      >
                        {CATEGORIES.map((c) => (
                          <option key={c} value={c}>
                            {c}
                          </option>
                        ))}
                      </select>
                    )}
                  </td>
                  <td className="border-r border-gray-200 p-0">
                    <input
                      type="text"
                      disabled={entry.isAutoGenerated}
                      defaultValue={entry.description || ""}
                      onBlur={(e) =>
                        handleCellChange(entry, "description", e.target.value)
                      }
                      placeholder={
                        entry.isAutoGenerated ? entry.source : "Description"
                      }
                      className="w-full h-full min-h-10 px-3 bg-transparent outline-none focus:bg-blue-50 focus:ring-1 focus:ring-blue-500 disabled:opacity-50 disabled:cursor-not-allowed"
                    />
                  </td>
                  <td className="border-r border-gray-200 p-0">
                    <input
                      type="number"
                      step="0.01"
                      disabled={entry.isAutoGenerated}
                      defaultValue={entry.amount}
                      onBlur={(e) =>
                        handleCellChange(entry, "amount", e.target.value)
                      }
                      className={`w-full h-full min-h-10 px-3 bg-transparent outline-none text-right font-mono font-medium focus:bg-blue-50 focus:ring-1 focus:ring-blue-500 disabled:opacity-50 disabled:cursor-not-allowed ${entry.type === "INCOME" ? "text-emerald-700" : "text-red-700"}`}
                    />
                  </td>
                  <td className="p-0 text-center align-middle">
                    {!entry.isAutoGenerated && (
                      <button
                        onClick={() => deleteMutation.mutate(entry.id)}
                        className="text-gray-400 hover:text-red-600 transition-colors mx-auto p-1.5 opacity-0 group-hover:opacity-100"
                        title="Delete manual entry"
                      >
                        <Trash2 className="w-4 h-4" />
                      </button>
                    )}
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      </div>
    </div>
  );
}
