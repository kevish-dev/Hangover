import { z } from "zod";

export const crmLeadSources = ["WEBSITE", "PHONE", "WHATSAPP", "REFERRAL", "WALK_IN", "MANUAL"];
export const crmLeadStages = ["NEW", "CONTACTED", "QUALIFIED", "QUOTE_SENT", "CONVERTED", "LOST"];
export const crmActivityTypes = ["NOTE", "CALL", "EMAIL", "WHATSAPP", "STATUS_CHANGE", "TASK_EVENT", "SYSTEM"];
export const crmTaskPriorities = ["LOW", "MEDIUM", "HIGH", "URGENT"];
export const crmTaskStatuses = ["OPEN", "DONE", "CANCELLED"];
export const crmTaskCategories = ["FOLLOW_UP", "PAYMENT", "TRAVELER_DOCUMENT", "HOTEL", "TRANSPORT", "PERMIT", "VENDOR", "GENERAL"];
export const tripTypes = [
  "MOUNTAIN_TREK",
  "BEACH_ESCAPE",
  "DESERT_EXPEDITION",
  "JUNGLE_WILDLIFE",
  "HERITAGE_WALK",
  "ROAD_TRIP",
  "BACKPACKING_TOUR",
  "PHOTOGRAPHY_TOUR",
  "BONFIRE_RETREAT",
  "INSTITUTE_COLLEGE_TRIP",
  "CUSTOM_TRIP",
];

const id = z.string().uuid();
const nullableId = id.nullable().optional();
const optionalDate = z.union([z.coerce.date(), z.null()]).optional();
const optionalText = (max) => z.string().trim().max(max).nullable().optional();
const tags = z.array(z.string().trim().min(1).max(40)).max(20).optional();
const pageQuery = {
  page: z.coerce.number().int().min(1).default(1),
  limit: z.coerce.number().int().min(1).max(100).default(25),
};

export const contactListQuerySchema = z.object({
  ...pageQuery,
  q: z.string().trim().max(160).optional(),
  source: z.enum(crmLeadSources).optional(),
  archived: z.enum(["false", "true", "all"]).default("false"),
});

export const createContactSchema = z.object({
  displayName: z.string().trim().min(1).max(160),
  email: z.string().trim().email().max(254).optional(),
  phone: z.string().trim().min(7).max(32).optional(),
  source: z.enum(crmLeadSources).default("MANUAL"),
  tags,
  userId: id.optional(),
}).refine((data) => data.email || data.phone || data.userId, {
  message: "Provide an email, phone number, or registered user.",
});

export const updateContactSchema = z.object({
  displayName: z.string().trim().min(1).max(160).optional(),
  email: z.string().trim().email().max(254).nullable().optional(),
  phone: z.string().trim().min(7).max(32).nullable().optional(),
  source: z.enum(crmLeadSources).optional(),
  tags,
  userId: nullableId,
  archived: z.boolean().optional(),
}).refine((data) => Object.keys(data).length > 0, { message: "No contact changes supplied." });

export const leadListQuerySchema = z.object({
  ...pageQuery,
  q: z.string().trim().max(160).optional(),
  stage: z.enum(crmLeadStages).optional(),
  source: z.enum(crmLeadSources).optional(),
  ownerId: id.optional(),
  tripId: id.optional(),
  festivalId: id.optional(),
  archived: z.enum(["false", "true", "all"]).default("false"),
});

export const createLeadSchema = z.object({
  contactId: id.optional(),
  displayName: z.string().trim().min(1).max(160).optional(),
  email: z.string().trim().email().max(254).optional(),
  phone: z.string().trim().min(7).max(32).optional(),
  tags,
  source: z.enum(crmLeadSources).default("MANUAL"),
  stage: z.enum(crmLeadStages).default("NEW"),
  tripId: id.optional(),
  festivalId: id.optional(),
  tripType: z.enum(tripTypes).optional(),
  bookingId: id.optional(),
  title: optionalText(200),
  details: optionalText(5000),
  ownerId: nullableId,
  nextFollowUpAt: optionalDate,
  lostReason: optionalText(1000),
}).refine(
  (data) => data.contactId || (data.displayName && (data.email || data.phone)),
  { message: "Provide contactId or new contact details." },
).refine((data) => !(data.tripId && data.festivalId), {
  message: "A lead can reference a trip or a festival, not both.",
}).refine((data) => data.stage !== "LOST" || Boolean(data.lostReason), {
  message: "A lost reason is required for lost leads.",
}).refine((data) => data.stage !== "CONVERTED" || Boolean(data.bookingId), {
  message: "A booking is required for converted leads.",
});

export const updateLeadSchema = z.object({
  stage: z.enum(crmLeadStages).optional(),
  tripId: nullableId,
  festivalId: nullableId,
  tripType: z.enum(tripTypes).nullable().optional(),
  bookingId: nullableId,
  title: optionalText(200),
  details: optionalText(5000),
  ownerId: nullableId,
  nextFollowUpAt: optionalDate,
  lostReason: optionalText(1000),
  archived: z.boolean().optional(),
}).refine((data) => Object.keys(data).length > 0, { message: "No lead changes supplied." });

export const createActivitySchema = z.object({
  contactId: id,
  leadId: id.optional(),
  bookingId: id.optional(),
  type: z.enum(crmActivityTypes).refine((type) => type !== "SYSTEM", {
    message: "SYSTEM activities are generated by the application.",
  }),
  summary: z.string().trim().min(1).max(240),
  details: optionalText(5000),
});

export const taskListQuerySchema = z.object({
  ...pageQuery,
  q: z.string().trim().max(160).optional(),
  status: z.enum(crmTaskStatuses).optional(),
  priority: z.enum(crmTaskPriorities).optional(),
  category: z.enum(crmTaskCategories).optional(),
  assigneeId: id.optional(),
  contactId: id.optional(),
  leadId: id.optional(),
  bookingId: id.optional(),
  tripId: id.optional(),
  festivalId: id.optional(),
  slotId: id.optional(),
  hotelReservationId: id.optional(),
  dueFrom: z.coerce.date().optional(),
  dueTo: z.coerce.date().optional(),
  archived: z.enum(["false", "true", "all"]).default("false"),
});

export const createTaskSchema = z.object({
  contactId: id.optional(),
  leadId: id.optional(),
  bookingId: id.optional(),
  tripId: id.optional(),
  festivalId: id.optional(),
  slotId: id.optional(),
  hotelReservationId: id.optional(),
  title: z.string().trim().min(1).max(200),
  description: optionalText(3000),
  category: z.enum(crmTaskCategories).default("GENERAL"),
  priority: z.enum(crmTaskPriorities).default("MEDIUM"),
  dueAt: optionalDate,
  assigneeId: nullableId,
}).refine((data) => data.contactId || data.leadId || data.bookingId || data.tripId || data.festivalId || data.slotId || data.hotelReservationId, {
  message: "Link the task to a contact, lead, booking, departure, trip, festival, or hotel reservation.",
});

export const updateTaskSchema = z.object({
  title: z.string().trim().min(1).max(200).optional(),
  description: optionalText(3000),
  category: z.enum(crmTaskCategories).optional(),
  priority: z.enum(crmTaskPriorities).optional(),
  status: z.enum(crmTaskStatuses).optional(),
  dueAt: optionalDate,
  assigneeId: nullableId,
  archived: z.boolean().optional(),
}).refine((data) => Object.keys(data).length > 0, { message: "No task changes supplied." });
